            "I": glyph = {5'b01110, 5'b00100, 5'b00100, 5'b00100, 5'b00100, 5'b00100, 5'b01110};
            "J": glyph = {5'b00111, 5'b00010, 5'b00010, 5'b00010, 5'b10010, 5'b10010, 5'b01100};
