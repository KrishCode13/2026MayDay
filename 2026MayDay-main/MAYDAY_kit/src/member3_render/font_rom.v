// =====================================================================
// font_rom.v  --  SHARED 5x7 Font ROM (Member 3 menus & Member 4 cutscene)
// Supports: 'A'-'Z' (and 'a'-'z'), '0'-'9' (both ASCII and raw 8'd0..9),
// space, ':', '/', '+', '!', '-'.
// =====================================================================
module font_rom (
    input  wire [7:0] char_code,
    input  wire [2:0] row,
    output reg  [4:0] pixels
);

    reg [7:0] norm_char;
    always @* begin
        if (char_code <= 8'd9)
            norm_char = char_code + 8'h30;
        else if (char_code >= "a" && char_code <= "z")
            norm_char = char_code - 8'h20;
        else
            norm_char = char_code;
    end

    reg [34:0] glyph; 
    always @* begin
        case (norm_char)
            "0": glyph = {5'b01110, 5'b10001, 5'b10011, 5'b10101, 5'b11001, 5'b10001, 5'b01110};
            "1": glyph = {5'b00100, 5'b01100, 5'b00100, 5'b00100, 5'b00100, 5'b00100, 5'b01110};
